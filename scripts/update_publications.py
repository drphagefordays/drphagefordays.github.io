#!/usr/bin/env python3
"""Rebuild the Publications list in index.html from an ORCID record.

Source of truth: the public ORCID record (works list) plus Crossref for the
details of each DOI (authors, journal, volume, pages). Entries that ORCID cannot
describe (thesis details, in-preparation work, overrides) live in
data/publications_manual.json and always win over the automatic ones.

Uses only the Python standard library. Exits non-zero on any network or data
problem so a scheduled run fails loudly instead of wiping the list.
"""
import html
import json
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORCID = "0000-0002-0025-3919"
UA = "personal-site-publications-updater/1.0 (+https://github.com/drphagefordays/drphagefordays.github.io)"
START = "<!-- pubs:start (generated by scripts/update_publications.py; edit data/publications_manual.json instead) -->"
END = "<!-- pubs:end -->"

TYPE_MAP = {  # ORCID work type -> (filter group, tag, sort rank)
    "journal-article": ("article", "Article", 1),
    "review": ("review", "Review", 2),
    "dissertation-thesis": ("other", "Thesis", 3),
    "book-chapter": ("other", "Book chapter", 3),
    "preprint": ("other", "Preprint", 3),
    "conference-paper": ("other", "Conference", 3),
}


def get_json(url, headers=None, tries=3):
    last = None
    for i in range(tries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/json", **(headers or {})})
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return None
            last = e
        except Exception as e:  # network hiccup
            last = e
        time.sleep(2 * (i + 1))
    raise RuntimeError("request failed: %s (%s)" % (url, last))


def norm(s):
    s = html.unescape(s or "").lower().replace("&", "and")
    return re.sub(r"[^a-z0-9]+", "", s)


def clean_title(t):
    t = re.sub(r"\s+", " ", t or "").strip()
    t = re.sub(r"<(/?)(?:i|em)>", lambda m: "\x00" + ("/" if m.group(1) else "") + "\x00", t, flags=re.I)
    t = re.sub(r"<[^>]+>", "", t)
    t = html.escape(html.unescape(t), quote=False)
    return t.replace("\x00/\x00", "</em>").replace("\x00\x00", "<em>")


def initials(given):
    parts = [p for p in re.split(r"[\s.\-]+", given or "") if p]
    return " ".join(p[0].upper() + "." for p in parts)


def is_me(a):
    return (a.get("family") or "").lower() == "parker" and (a.get("given") or "").strip().lower().startswith("d")


def format_authors(authors):
    if not authors:
        return "<strong>Parker, D. R.</strong>"

    def one(a):
        name = ("%s, %s" % (a.get("family", ""), initials(a.get("given", "")))).rstrip(", ")
        s = html.escape(name, quote=False)
        return "<strong>%s</strong>" % s if is_me(a) else s

    items = [one(a) for a in authors]
    if len(authors) > 8:
        head = items[:6]
        me = next((i for i, a in enumerate(authors) if is_me(a)), None)
        if me is not None and me >= 6:
            head.append("&hellip;")
            head.append(items[me])
        else:
            head.append("et al.")
        return ", ".join(head)
    if len(items) == 1:
        return items[0]
    return ", ".join(items[:-1]) + ", &amp; " + items[-1]


def crossref_year(msg, fallback):
    for key in ("published-print", "published", "issued"):
        try:
            return int(msg[key]["date-parts"][0][0])
        except (KeyError, IndexError, TypeError, ValueError):
            continue
    return fallback


def build_meta(msg, doi, group):
    venue = ""
    ct = (msg.get("container-title") or [""])[0]
    if ct:
        venue = "<em>%s</em>" % html.escape(ct, quote=False)
        if msg.get("volume"):
            venue += " " + html.escape(msg["volume"], quote=False)
            if msg.get("issue"):
                venue += "(%s)" % html.escape(msg["issue"], quote=False)
        if msg.get("page"):
            venue += ", " + html.escape(msg["page"].replace("-", "–"), quote=False)
        venue += "."
    elif msg.get("publisher"):
        venue = html.escape(msg["publisher"], quote=False) + "."
    link = ' <a class="doi" href="https://doi.org/%s" target="_blank" rel="noopener">doi:%s</a>' % (html.escape(doi, quote=True), html.escape(doi, quote=False))
    return "%s %s%s" % (format_authors(msg.get("author")), venue, link)


def fetch_orcid_works():
    data = get_json("https://pub.orcid.org/v3.0/%s/works" % ORCID)
    groups = (data or {}).get("group", [])
    works = []
    for g in groups:
        s = g["work-summary"][0]
        doi = None
        for ext in (g.get("external-ids") or {}).get("external-id", []):
            if ext.get("external-id-type") == "doi":
                doi = re.sub(r"^https?://(dx\.)?doi\.org/", "", ext["external-id-value"].strip(), flags=re.I).lower()
                break
        year = None
        try:
            year = int(s["publication-date"]["year"]["value"])
        except (KeyError, TypeError, ValueError):
            pass
        works.append({"title": s["title"]["title"]["value"], "type": s.get("type") or "other", "doi": doi, "year": year})
    return works


def main():
    manual = json.loads((ROOT / "data" / "publications_manual.json").read_text(encoding="utf-8"))
    exclude = {d.lower() for d in manual.get("exclude_dois", [])}
    manual_keys = {norm(e["title"]) for e in manual["entries"]}

    works = fetch_orcid_works()
    if not works:
        raise RuntimeError("ORCID returned no works; refusing to overwrite the list")

    entries = []
    for e in manual["entries"]:
        entries.append({"year": e["year"], "rank": e.get("rank", 3), "type": e["type"], "tag": e["tag"],
                        "title": clean_title(e["title"]), "meta": e["meta_html"]})

    for w in works:
        if norm(w["title"]) in manual_keys or (w["doi"] and w["doi"] in exclude):
            continue
        group, tag, rank = TYPE_MAP.get(w["type"], ("other", w["type"].replace("-", " ").capitalize(), 3))
        msg = None
        if w["doi"]:
            cr = get_json("https://api.crossref.org/works/%s" % urllib.parse.quote(w["doi"], safe=""))
            msg = (cr or {}).get("message")
            time.sleep(0.3)
        if msg:
            title = clean_title((msg.get("title") or [w["title"]])[0])
            year = crossref_year(msg, w["year"])
            meta = build_meta(msg, w["doi"], group)
        else:
            title = clean_title(w["title"])
            year = w["year"] or 0
            meta = "<strong>Parker, D. R.</strong>"
            if w["doi"]:
                meta += ' <a class="doi" href="https://doi.org/%s" target="_blank" rel="noopener">doi:%s</a>' % (w["doi"], w["doi"])
        entries.append({"year": year, "rank": rank, "type": group, "tag": tag, "title": title, "meta": meta})

    entries.sort(key=lambda e: (-e["year"], e["rank"], e["title"].lower()))
    items = []
    for e in entries:
        items.append(
            '          <li class="pub reveal" data-type="%s">\n'
            '            <span class="pub-year">%d</span>\n'
            '            <div><p class="pub-title">%s</p><p class="pub-meta">%s</p></div>\n'
            '            <span class="pub-tag">%s</span>\n'
            '          </li>' % (e["type"], e["year"], e["title"], e["meta"], e["tag"]))
    block = "          %s\n%s\n          %s" % (START, "\n".join(items), END)

    path = ROOT / "index.html"
    page = path.read_text(encoding="utf-8")
    if START in page and END in page:
        i = page.index(START)
        j = page.index(END) + len(END)
        line_start = page.rfind("\n", 0, i) + 1  # keep the marker's own indentation
        new = page[:line_start] + block + page[j:]
    else:
        m = re.search(r'(<ol class="pubs">\n)(.*?)(\n        </ol>)', page, flags=re.S)
        if not m:
            raise RuntimeError('could not find <ol class="pubs"> in index.html')
        new = page[:m.end(1)] + block + page[m.start(3):]
    if new != page:
        path.write_text(new, encoding="utf-8")
        print("Publications updated: %d entries" % len(entries))
    else:
        print("No changes: %d entries" % len(entries))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        sys.exit(1)
